import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {setLanguage,t,L} from '../language.js';
import {renderHUD} from '../hud-layout.js';
const catalog=JSON.parse(readFileSync(new URL('../assets/language.json',import.meta.url)));
assert.equal(catalog.count,4321);
assert.equal(catalog.sha256,createHash('sha256').update(readFileSync(new URL('../../../DataTable/en-gb/Language.xlsx',import.meta.url))).digest('hex'));
setLanguage(catalog);
assert.equal(t(1087),'General Info');
assert.equal(t(1094),' Level:');
assert.equal(t(1155,2),'Bag 2');
assert.equal(t(1146,'Inventory','I'),"Inventory\nShortcut 'I'");
assert.equal(t(1122,.98),'0.98 Faster');
assert.throws(()=>t(1155),/missing argument/);
assert.throws(()=>t(1087,'unexpected'),/extra argument/);
assert.throws(()=>t(999999),/missing serial/);
const html=renderHUD();
assert(html.includes('rfItemTooltip')&&html.includes('rfInfo-resistance'));
assert(!html.includes('Selamat datang')&&!html.includes('99.99%'));
for(const [,id] of html.matchAll(/data-language-id="(\d+)"/g))assert.equal(typeof catalog.phrases[id],'string');
setLanguage({count:1,phrases:{0:'<img src=x onerror=alert(1)>'}});
assert.equal(L(0),'<span data-language-id="0">&lt;img src=x onerror=alert(1)&gt;</span>');
setLanguage(catalog);
